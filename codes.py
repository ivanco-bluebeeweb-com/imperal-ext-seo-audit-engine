"""Структурные коды ошибок.

Прямой урок из WP Publisher: ошибка без кода получает от ядра штамп
`EXT_UNSTRUCTURED_ERROR`, и точный сбой превращается в бесполезную прозу.
Правило валидатора V32 ищет только буквальные вызовы `ActionResult.error(`,
поэтому приложение, которое маршрутизирует ошибки через свой хелпер, для
правила невидимо — именно так баг и уехал в прод в прошлый раз.

Отсюда конструкция: в `shared.error(message, code)` код — ОБЯЗАТЕЛЬНЫЙ
позиционный аргумент. Забыть его невозможно: это TypeError при написании кода,
а не тихая деградация у пользователя. Тест обходит AST всех модулей и падает,
если найдёт путь ошибки без кода.
"""

