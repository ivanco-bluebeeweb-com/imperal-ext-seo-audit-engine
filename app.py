"""Объявление расширения SEO Audit Engine.

АРХИТЕКТУРА: расширение — это ОБЁРТКА над движком `seoaudit`, а не его копия.

Движок (`seoaudit/`) — самостоятельный пакет на одной стандартной библиотеке:
обходит сайты, применяет 18 правил, строит задачи. Он уже покрыт 28 тестами и
работает как CLI. Расширение не переписывает эту логику, оно её ВЫЗЫВАЕТ и
переводит результат в сущности платформы. Поэтому правило аудита правится в
одном месте и одинаково действует и в терминале, и в чате.

ГРАНИЦА: аудит ТОЛЬКО ЧИТАЕТ чужие сайты.
Ни один инструмент здесь ничего не меняет на сайте — отсюда нет ни одного
`action_type="write"` в адрес аудируемого сайта. Правки вносит отдельное
приложение (`wp-site-connector`) и только по подтверждённой задаче. Разделение
намеренное: процесс, который ходит по чужим сайтам, не должен иметь прав на
запись. `capabilities` объявлены явно, чтобы ядро проверяло
`tool.required_scopes ⊆ declared` вместо выдачи wildcard-скоупа (V34).

ПОЧЕМУ `urllib`, А НЕ `ctx.http`.
Движок фетчит страницы сам через `urllib` в пуле потоков. Так и задумано:
аудит делает сотни запросов к ОДНОМУ чужому сайту с вежливыми лимитами
(задержка между запросами, ограничение параллельности на хост, соблюдение
robots.txt) — эта дисциплина живёт внутри движка и должна работать одинаково
из CLI и из платформы. Документация прямо говорит: прямой `urllib`
не рекомендуется, но федерально НЕ запрещён (запрещён только прямой импорт
LLM-провайдеров, V7). Обёртка над `ctx.http` дала бы асинхронный клиент без
этих лимитов и потребовала бы переписать движок — цена выше пользы.

ПОЧЕМУ ДОЛГИЙ ПРОГОН — ФОНОВАЯ ЗАДАЧА.
Аудит 20 сайтов — это минуты, 200 сайтов — до 22 минут. Федеральный предел
одного вызова — 180 с, фоновой задачи с `long_running=True` — 1800 с. Поэтому
инструмент аудита сразу возвращает подтверждение и отдаёт работу в
`ctx.background_task(..., long_running=True)`: чат не блокируется, а результат
платформа доставит отдельным сообщением. Больше 1800 с не обещаем — предел
прогона ограничен явно, и об этом сказано в описании инструмента.

ГДЕ ЖИВУТ ДАННЫЕ.
База прогона — SQLite движка. Она пишется во временный каталог воркера и
поднимается в `ctx.storage` под ключом пользователя, потому что диск воркера
между вызовами не сохраняется. Сводка прогона дополнительно кладётся в
`ctx.store` — так панель показывает историю, не скачивая базу.
"""

from imperal_sdk import Extension, ChatExtension

ext = Extension(
    "seo-audit-engine",
    version="1.0.0",
    # Только чтение чужих сайтов + запись СВОИХ результатов прогона.
    # Здесь намеренно нет ничего вида "site:write".
    capabilities=["seo:audit", "seo:report"],
    display_name="SEO Audit Engine",
    description=(
        "Технический SEO-аудит портфеля сайтов: обход страниц, 18 правил в "
        "шести слоях, отчёты по каждому сайту и по портфелю, и готовые задачи "
        "для трекера. Только чтение — аудит ничего не меняет на сайтах."
    ),
    icon="icon.svg",
    actions_explicit=True,
)

chat = ChatExtension(
    ext,
    tool_name="seo_audit",
    description=(
        "SEO Audit Engine — проверить сайты на технические SEO-дефекты, "
        "посмотреть находки и отчёты, получить план задач для трекера."
    ),
)


@ext.health_check
async def health_check(ctx) -> dict:
    """Готовность приложения: движок импортируется, прогоны доступны.

    Намеренно НЕ ходит в сеть и не трогает чужие сайты: проверка живости
    должна быть быстрой и не падать из-за того, что чей-то сайт лежит.
    Отвечает на вопрос «приложение работоспособно», а не «сайты доступны».
    """
    try:
        from seoaudit.rules import ALL_RULES
        rules = len(ALL_RULES)
    except Exception as exc:  # движок не собрался — это единственная реальная поломка
        return {
            "healthy": False,
            "detail": f"Движок аудита не импортируется: {type(exc).__name__}",
        }

    runs = 0
    try:
        runs = await ctx.store.count("seo_runs")
    except Exception:
        runs = 0

    return {
        "healthy": True,
        "rules": rules,
        "runs_recorded": runs,
        "detail": f"Готово: {rules} правил, прогонов записано {runs}.",
    }


@ext.on_install
async def on_install(ctx):
    """Приложение работоспособно сразу — ему не нужны ни ключи, ни доступы.

    Записываю это в журнал явно: в отличие от коннекторов, свежая установка
    здесь НЕ инертна, и «ничего не настроено» не должно выглядеть как поломка.
    """
    await ctx.log(
        "SEO Audit Engine установлен — настройка не требуется, "
        "аудит запускается сразу: «проверь climtec.md».",
        level="info",
    )
